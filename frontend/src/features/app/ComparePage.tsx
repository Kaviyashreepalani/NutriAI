import React, { useEffect, useState } from 'react';
import { Link } from 'react-router-dom';
import { api } from '../../lib/api';
import { Card } from '../../components/ui/Card';
import { Button } from '../../components/ui/Button';
import { PrototypeBadge } from '../../components/safety/PrototypeBadge';
import { MedicalDisclaimer } from '../../components/safety/MedicalDisclaimer';
import { EmptyState } from '../../components/ui/EmptyState';
import { Scale, FlaskConical, Info } from 'lucide-react';

export const ComparePage: React.FC = () => {
  const [formulations, setFormulations] = useState<any[]>([]);
  const [selected, setSelected] = useState<string[]>([]);
  const [compareData, setCompareData] = useState<any[]>([]);
  const [loading, setLoading] = useState(true);
  const [comparing, setComparing] = useState(false);

  useEffect(() => {
    const fetchFormulations = async () => {
      try {
        const res = await api.get('/formulations');
        setFormulations(res.data || []);
      } finally {
        setLoading(false);
      }
    };
    fetchFormulations();
  }, []);

  const handleToggleSelect = (id: string) => {
    setSelected((prev) =>
      prev.includes(id) ? prev.filter((s) => s !== id) : prev.length < 3 ? [...prev, id] : prev
    );
  };

  const handleCompare = async () => {
    if (selected.length < 2) return;
    setComparing(true);
    try {
      const res = await api.post('/formulations/compare', { ids: selected });
      setCompareData(res.data || []);
    } finally {
      setComparing(false);
    }
  };

  const COMPARE_ROWS = [
    { key: 'product_name', label: 'Product Name' },
    { key: 'format', label: 'Format' },
    { key: 'serving_size_g', label: 'Serving Size (g)', suffix: 'g' },
    { key: 'iron_mg', label: 'Iron per Serving (mg)', suffix: ' mg' },
    { key: 'vitc_mg', label: 'Vitamin C (mg)', suffix: ' mg' },
    { key: 'bioavailability_index', label: 'Bioavailability Index', isPercent: true },
    { key: 'cost_inr', label: 'Est. Cost per Serving (₹)', prefix: '₹' },
    { key: 'diet_class', label: 'Diet Class' },
  ];

  if (loading) return <div className="h-64 bg-gray-200 rounded-2xl animate-pulse" />;

  return (
    <div className="max-w-5xl mx-auto space-y-6">
      <div className="flex items-center justify-between">
        <div>
          <h1 className="text-xl font-bold text-gray-900">Compare Formulations</h1>
          <p className="text-sm text-gray-600 mt-0.5">Select 2–3 formulations to compare side-by-side.</p>
        </div>
        <PrototypeBadge />
      </div>

      <div className="p-3 rounded-xl bg-primary-50 border border-primary-200 flex gap-2 text-xs text-primary-800">
        <Info className="w-4 h-4 text-primary-600 shrink-0 mt-0.5" />
        <span>All values are computed deterministically from IFCT 2017 reference data. No values are estimated or generated by AI.</span>
      </div>

      {formulations.length === 0 ? (
        <EmptyState
          icon={<FlaskConical className="w-10 h-10 text-gray-400" />}
          title="No formulations to compare"
          description="Generate at least 2 formulations to use the compare feature."
          action={<Link to="/app/generate"><Button variant="primary">Generate Formulation</Button></Link>}
        />
      ) : (
        <>
          {/* Selector Grid */}
          <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-3 gap-3">
            {formulations.map((f: any) => {
              const isSelected = selected.includes(f.id);
              const isDisabled = !isSelected && selected.length >= 3;
              return (
                <button
                  key={f.id}
                  onClick={() => handleToggleSelect(f.id)}
                  disabled={isDisabled}
                  className={`p-4 rounded-xl border text-left transition ${
                    isSelected
                      ? 'border-primary-500 bg-primary-50 ring-2 ring-primary-300'
                      : isDisabled
                      ? 'border-gray-200 bg-gray-50 opacity-50 cursor-not-allowed'
                      : 'border-gray-200 bg-white hover:border-primary-300'
                  }`}
                >
                  <div className="flex items-center justify-between mb-1">
                    <span className="text-xs font-bold text-gray-900 leading-tight">{f.product_name}</span>
                    {isSelected && (
                      <span className="text-[10px] font-bold text-primary-700 bg-primary-100 px-1.5 py-0.5 rounded">Selected</span>
                    )}
                  </div>
                  <p className="text-[11px] text-gray-500">{f.format} • {f.iron_mg} mg Fe • ₹{f.cost_inr}</p>
                  <p className="text-[10px] text-gray-400 mt-1">{new Date(f.created_at).toLocaleDateString()}</p>
                </button>
              );
            })}
          </div>

          <Button
            variant="primary"
            disabled={selected.length < 2 || comparing}
            onClick={handleCompare}
            className="w-full sm:w-auto"
          >
            <Scale className="w-4 h-4 mr-2" />
            {comparing ? 'Comparing…' : `Compare ${selected.length} Formulation${selected.length !== 1 ? 's' : ''}`}
          </Button>

          {/* Comparison Table */}
          {compareData.length >= 2 && (
            <div className="overflow-x-auto rounded-xl border border-gray-200">
              <table className="w-full text-xs text-left">
                <thead className="bg-gray-50 border-b border-gray-200">
                  <tr>
                    <th className="px-4 py-3 font-semibold text-gray-700 w-40">Metric</th>
                    {compareData.map((f: any, i: number) => (
                      <th key={i} className="px-4 py-3 font-semibold text-gray-900">{f.product_name}</th>
                    ))}
                  </tr>
                </thead>
                <tbody className="divide-y divide-gray-100 bg-white">
                  {COMPARE_ROWS.map((row) => (
                    <tr key={row.key} className="hover:bg-gray-50">
                      <td className="px-4 py-3 font-medium text-gray-600">{row.label}</td>
                      {compareData.map((f: any, i: number) => {
                        const val = f[row.key];
                        const formatted = row.isPercent
                          ? `${(val * 100).toFixed(0)}%`
                          : `${row.prefix || ''}${typeof val === 'number' ? val.toFixed(1) : val}${row.suffix || ''}`;
                        return (
                          <td key={i} className="px-4 py-3 font-mono text-gray-900">{formatted}</td>
                        );
                      })}
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          )}
        </>
      )}

      <MedicalDisclaimer />
    </div>
  );
};

